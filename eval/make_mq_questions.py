"""
Make the MULTI-QUERY test set: 40 new questions, generated by Claude from our papers.
  - 20 one-part questions: written from ONE page            (answer key: that page)
  - 20 two-part questions: written from TWO pages of two     (answer key: both pages; a full answer needs both)
    different papers on related topics

The two groups are reported separately: multi-query should HELP two-part questions without HURTING one-part ones.
Pages used by earlier generated test sets are never reused.

Uses the Claude API key from .env (run this yourself; about $0.30). Saves after every question to
eval/synthetic_mq.json (split "mq"), so a stopped run continues where it left off.

Run:  python eval/make_mq_questions.py
Then: python eval/decompose_questions.py     (Claude splits each question into sub-questions)
"""

import json
import random
import sys
from pathlib import Path

import anthropic
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")
sys.path.insert(0, str(ROOT / "src"))
from retrieve import hybrid_ranking, load_chunks  # noqa: E402

OUT_FILE = ROOT / "eval/synthetic_mq.json"
MODEL = "claude-sonnet-5-5"
PRICE_PER_MTOK = {"input": 2.00, "output": 10.00}  # Sonnet 5.5, USD per million tokens
N_PER_GROUP = 20
SEED = 31
MIN_TOKENS = 150
SKIP_SECTIONS = ("method", "material", "statistic", "patient selection", "study design", "procedure")
PARTNER_RANKS = range(10, 41)  # a related page (same broad topic) but not a near-duplicate of the first

ONE_SCHEMA = {
    "type": "object",
    "properties": {"usable": {"type": "boolean"}, "question": {"type": "string"},
                   "reference_answer": {"type": "string"},
                   "must_include": {"type": "array", "items": {"type": "string"}}},
    "required": ["usable", "question", "reference_answer", "must_include"], "additionalProperties": False,
}
TWO_SCHEMA = {
    "type": "object",
    "properties": {"usable": {"type": "boolean"}, "question": {"type": "string"},
                   "reference_answer": {"type": "string"},
                   "facts_from_a": {"type": "array", "items": {"type": "string"}},
                   "facts_from_b": {"type": "array", "items": {"type": "string"}}},
    "required": ["usable", "question", "reference_answer", "facts_from_a", "facts_from_b"],
    "additionalProperties": False,
}

COMMON_RULES = """- The question must make sense on its own: never say "this study", "the passage", "the authors" or "Table 2".
- Ask it the way a student, researcher or clinician would; don't copy long phrases from the passages.
- It must be a research question about the literature, not advice for a specific person.
- reference_answer: the correct answer in 1-3 sentences, using only what the passage(s) say."""

ONE_INSTRUCTIONS = f"""You help build an evaluation set for a search tool over research papers on CAR-T cell \
therapy. Read the passage and write ONE question that this passage answers.
{COMMON_RULES}
- must_include: 1-2 short key facts a correct answer must contain.
- If the passage has nothing worth asking about (references, acknowledgements, pure methods), set usable to \
false and leave the other fields empty."""

TWO_INSTRUCTIONS = f"""You help build an evaluation set for a search tool over research papers on CAR-T cell \
therapy. You get two passages, A and B, from different papers. Write ONE natural question with TWO parts, where \
a full answer needs facts from BOTH passages (for example "How do X and Y compare…", "What are X, and how does \
Y…"). Each part must be answered by its own passage.
{COMMON_RULES}
- facts_from_a / facts_from_b: 1-2 short key facts from each passage that a full answer must contain.
- If no natural question can combine the two passages, set usable to false and leave the other fields empty."""


def eligible(c: dict) -> bool:
    sections = " ".join(c["sections"]).lower()
    return c["n_tokens"] >= MIN_TOKENS and not any(s in sections for s in SKIP_SECTIONS)


def ask(client, system, content, schema):
    response = client.messages.create(
        model=MODEL, max_tokens=4000, system=system, messages=[{"role": "user", "content": content}],
        output_config={"effort": "low", "format": {"type": "json_schema", "schema": schema}},
    )
    cost = (response.usage.input_tokens * PRICE_PER_MTOK["input"]
            + response.usage.output_tokens * PRICE_PER_MTOK["output"]) / 1_000_000
    if response.stop_reason == "refusal":
        return None, cost
    return json.loads(next(b.text for b in response.content if b.type == "text")), cost


def passage(label: str, c: dict) -> str:
    return f'<passage id="{label}">\nPaper: {c["title"]}\n\n{c["text"]}\n</passage>'


def main():
    chunks = load_chunks()
    by_pos = dict(enumerate(chunks))
    used = set()
    for f in (ROOT / "eval").glob("synthetic*.json"):
        if f != OUT_FILE:
            for q in json.loads(f.read_text()):
                used.update(q["relevant_chunks"])
    questions = json.loads(OUT_FILE.read_text()) if OUT_FILE.exists() else []
    for q in questions:
        used.update(q["relevant_chunks"])
    pool = [c for c in chunks if eligible(c) and c["chunk_id"] not in used]
    random.Random(SEED).shuffle(pool)

    client = anthropic.Anthropic()
    cost = 0.0

    def save():
        OUT_FILE.write_text(json.dumps(questions, indent=2, ensure_ascii=False), encoding="utf-8")

    def count(kind):
        return sum(1 for q in questions if q["type"] == kind)

    for c in pool:
        if count("one_part") >= N_PER_GROUP and count("two_part") >= N_PER_GROUP:
            break
        if c["chunk_id"] in used:
            continue
        if count("two_part") < N_PER_GROUP:
            # Two-part: pair this page with a related page from a different paper
            partner = None
            for rank, (pos, _) in enumerate(hybrid_ranking(c["text"][:1000])[:max(PARTNER_RANKS) + 1], 1):
                p = by_pos[pos]
                if rank in PARTNER_RANKS and p["pmcid"] != c["pmcid"] and eligible(p) and p["chunk_id"] not in used:
                    partner = p
                    break
            if not partner:
                continue
            result, k = ask(client, TWO_INSTRUCTIONS, passage("A", c) + "\n\n" + passage("B", partner), TWO_SCHEMA)
            cost += k
            used.update({c["chunk_id"], partner["chunk_id"]})
            if result and result["usable"] and result["question"].strip():
                qid = f"m{len(questions) + 1:02d}"
                questions.append({
                    "id": qid, "question": result["question"].strip(), "type": "two_part", "checks": [],
                    "split": "mq", "answerable": True, "reference_answer": result["reference_answer"].strip(),
                    "expected_behavior": None, "must_include": result["facts_from_a"] + result["facts_from_b"],
                    "must_not": [], "relevant_papers": [c["pmcid"], partner["pmcid"]],
                    "relevant_chunks": [c["chunk_id"], partner["chunk_id"]],  # BOTH are needed for a full answer
                    "added_by_method_b": [], "label_quality": "approximate", "generated_by": MODEL,
                })
                save()
                print(f"[{qid}] two-part  {result['question'][:85]}")
        else:
            result, k = ask(client, ONE_INSTRUCTIONS, passage("A", c), ONE_SCHEMA)
            cost += k
            used.add(c["chunk_id"])
            if result and result["usable"] and result["question"].strip():
                qid = f"m{len(questions) + 1:02d}"
                questions.append({
                    "id": qid, "question": result["question"].strip(), "type": "one_part", "checks": [],
                    "split": "mq", "answerable": True, "reference_answer": result["reference_answer"].strip(),
                    "expected_behavior": None, "must_include": result["must_include"], "must_not": [],
                    "relevant_papers": [c["pmcid"]], "relevant_chunks": [c["chunk_id"]],
                    "added_by_method_b": [], "label_quality": "approximate", "generated_by": MODEL,
                })
                save()
                print(f"[{qid}] one-part  {result['question'][:85]}")

    print(f"\n{count('two_part')} two-part + {count('one_part')} one-part questions -> {OUT_FILE}  "
          f"(this run cost ${cost:.2f})")


if __name__ == "__main__":
    main()
